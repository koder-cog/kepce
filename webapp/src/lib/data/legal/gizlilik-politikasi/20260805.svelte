<p>
  Gizlilik Politikamızı, 6698 sayılı Kişisel Verilerin Korunması Kanunu ve
  ilgili mevzuat kapsamındaki gereklilikler çerçevesinde, Kepçe (kepce.org)
  internet sitesi ve ilgili hizmetlerimize erişirken sağlayacağınız kişisel
  verilerinizin korunması hakkında sizi aydınlatmak amacıyla oluşturduk.
</p>

<section>
  <h2>1. Veri Sorumlusu</h2>
  <p>
    KVKK kapsamında Veri Sorumlusu sıfatıyla hareket eden, Kazım Geleş
    tarafından bireysel olarak geliştirilen Kepçe Projesi'dir. Resmi tebligat
    veya Uyar-Kaldır bildirimleri için
    <a href="/iletisim" data-link>iletişim sayfamız</a> üzerinden bizimle irtibat
    kurabilirsiniz.
  </p>
</section>

<section>
  <h2>2. Toplanan Kişisel Veriler ve İşlenme Amaçları</h2>
  <p>
    Kepçe, ticari kâr veya davranışsal profil çıkarma amacı gütmeyen açık
    kaynaklı bir organizasyon modeliyle çalışır. Toplanan veriler, yalnızca
    kullanıcı faydası gözetilerek asgari oranda işlenmekte olup aşağıdaki
    şekilde kategorize edilir:
  </p>
  <ul>
    <li>
      <strong>Ziyaretçi Verileri:</strong> Sisteme herhangi bir hesaba giriş
      yapmaksızın erişmeniz durumunda otomatik olarak işlem tarihi, saati, IP
      adresleri ve port bilgileri, görüntülenen sayfalar, ziyaret süreleri,
      tarayıcı/cihaz modelinize ilişkin veriler ile
      <strong
        >IP adresiniz üzerinden otomatik tespit edilen yaklaşık konum (şehir)
        bilginiz</strong
      > elde edilmektedir. Bu bilgiler, yasal yükümlülüklerin yanı sıra size doğrudan
      doğru şehre ait menüyü göstermek amacıyla anlık olarak işlenir.
    </li>
    <li>
      <strong>Kullanıcı Etkileşim Verileri:</strong> Uygulama üzerinden hesaba
      giriş yapılarak veya yapılmaksızın gerçekleştirilen günlük yurt yemekleri
      oylamaları, tabldot yorumlar ve serbest yorumlar gibi platform içi üretimler
      sistemimize kaydedilir.
    </li>
    <li>
      <strong>Hesap ve Kimlik Verileri:</strong> Giriş yaparken veya kayıt olurken
      doğrudan paylaştığınız kullanıcı kimliği, e-posta adresi ve giriş platformu
      gibi kayıtlar.
    </li>
    <li>
      <strong>Aktif Oturum Verileri:</strong> Hesabınıza giriş yapıldığında,
      hesap güvenliğinin sağlanması, yetkisiz girişlerin tespit edilmesi ve
      aktif oturumlarınızı dilediğiniz an sonlandırabilmeniz amacıyla
      <strong
        >giriş yapılan IP adresi, giriş tarihi ve tarayıcı (User-Agent)</strong
      > bilgileriniz veritabanımızda saklanır.
    </li>
  </ul>
  <p>
    Bu veriler; platform güvenliğinin sağlanması, platform kurallarına uymayan
    içeriklerin engellenmesi, hizmet kalitesinin ve kullanıcı deneyiminin
    sürdürülebilirliğinin sağlanması, KVKK ile 5651 sayılı kanun kapsamındaki
    başvuruların değerlendirilerek hukuki yükümlülüklerimizin yerine
    getirilebilmesi amacıyla işlenmektedir. Kepçe, veri satışından veya
    hedefli reklamcılıktan hiçbir gelir elde etmez.
  </p>
</section>

<section>
  <h2>3. Kişisel Verilerin Toplanma Yöntemi ve Hukuki Sebepleri</h2>
  <p>
    Topladığımız veriler, KVKK’nin 5. maddesinde belirtilen aşağıdaki hukuki
    sebeplere dayalı olarak, ziyaretiniz sırasında tamamen veya kısmen
    otomatik yollarla toplanmaktadır:
  </p>
  <ul>
    <li>Kanunlarda açıkça öngörülmesi (5651 sayılı Kanun yükümlülükleri).</li>
    <li>
      Veri sorumlusunun hukuki yükümlülüklerini yerine getirebilmesi için
      zorunlu olması.
    </li>
    <li>
      İlgili kişinin temel hak ve özgürlüklerine zarar vermemek kaydı ile veri
      sorumlusunun meşru menfaatleri için veri işlenmesinin zorunlu olması.
    </li>
  </ul>
</section>

<section>
  <h2>4. Kişisel Verilerin Aktarılması ve Yurtdışı Sunucuları</h2>
  <p>
    Hukuki ve yasal zorunluluklar devreye girmediği sürece kişisel verileriniz
    yetkisiz üçüncü kişiler ile paylaşılmamaktadır. Yetkili adli mercilerden
    (Mahkemeler, Savcılıklar vb.) gelen usulüne uygun talepler gereğince,
    ilgili mercilere verilerin iletilmesi yasal bir yükümlülüktür.
  </p>
  <p>
    Kepçe projesinin kullandığı bulut sunucular yurtdışında (Marsilya/Fransa)
    bulunmaktadır. 6698 sayılı KVKK'nın 9. maddesi hükümleri uyarınca,
    verilerinizin yurtdışındaki bu sunucularda barındırılması işlemi; altyapı
    sağlayıcımız ile yapılan standart sözleşmeler ve sağlanan uygun
    güvencelere (veri güvenliği taahhütleri) dayalı olarak
    gerçekleştirilmektedir.
  </p>
</section>

<section>
  <h2>5. 5651 Sayılı Kanun Kapsamında Saklama Süreleri</h2>
  <p>
    5651 sayılı yasaya istinaden "Yer Sağlayıcı" olarak faaliyet
    göstermekteyiz. Bu kanun uyarınca; sisteme erişen kullanıcıların işlem
    tarihi, saati, IP adresleri ve port bilgileri gibi trafik verileri yasal
    zorunluluk gereği <strong
      >1 yıldan az ve 2 yıldan fazla olmamak üzere</strong
    >
    saklanmaktadır. Kullanıcı hesapları ve girilen içerikler (yorumlar, oylamalar
    vb.), ilgili hesap silindiğinde veya resmi/hukuki taleple kaldırıldığında KVKK
    Madde 7 gereği derhal kalıcı olarak imha edilir veya anonimleştirilir.
  </p>
</section>

<section>
  <h2>6. Tarayıcı Depolama ve Üçüncü Parti Hizmetler</h2>
  <p>
    Platformun temel fonksiyonlarının çalışabilmesi, şehir tercihinizin
    hatırlanması ve oturum güvenliğinin sağlanması amacıyla zorunlu çerezler
    (essential cookies) ile tarayıcınızın Local Storage ve Session Storage
    özelliklerinden yararlanılır.
  </p>
  <p>
    Platformumuzun altyapı, analitik ve güvenlik hizmetleri için üçüncü parti servis
    sağlayıcılarından (kimlik doğrulama hizmetleri, CDN/güvenlik altyapısı
    vb.) yararlanılabilmektedir. Bu kapsamda uygulamamızdaki hataları ve performans
    sorunlarını tespit etmek için <strong>Sentry</strong> ve anonim web istatistiklerini
    toplamak için <strong>Umami</strong> kullanılabilmektedir. Bu servislerle ilgili veri işleme
    faaliyetleri hakkında detaylı bilgi almak için ilgili sağlayıcıların
    gizlilik politikalarını incelemenizi tavsiye ederiz. Kepçe, bu
    entegrasyonlardan doğan veri işleme faaliyetleri bakımından KVKK
    kapsamındaki sorumluluklarını saklı tutar.
  </p>
</section>

<section>
  <h2>7. Yaş Sınırı Beyanı</h2>
  <p>
    Kepçe’nin temel hedef kitlesi üniversite öğrencileri olsa da, 18 yaşının
    altındaki (örneğin 17 yaşında üniversiteye başlayan) bireylerin platforma
    kayıt olması ve kişisel verilerini paylaşması hukuken veli/vasi onayına
    tabidir. Eğer 18 yaşının altındaki bir kullanıcının yasal temsilcisinin
    rızası olmaksızın kişisel verilerini paylaştığından haberdar olursak, bu
    veriler KVKK gereği derhal imha edilecektir. Reşit olmayan öğrencilerin
    sistemi yasal temsilcilerinin gözetimi ve rızasıyla kullanması kendi
    sorumluluklarındadır.
  </p>
</section>

<section>
  <h2>8. İlgili Kişinin Hakları</h2>
  <p>KVKK’nın 11. maddesi uyarınca kişisel veri sahipleri;</p>
  <ul>
    <li>
      Kişisel veri işlenip işlenmediğini öğrenme, işlenmişse bilgi talep etme,
    </li>
    <li>
      İşlenme amacını ve amacına uygun kullanılıp kullanılmadığını öğrenme,
    </li>
    <li>
      Yurt içinde veya yurt dışındaki kişisel verilerin aktarıldığı üçüncü
      kişileri bilme,
    </li>
    <li>
      Kişisel verilerin eksik veya yanlış işlenmiş olması hâlinde bunların
      düzeltilmesini isteme,
    </li>
    <li>
      KVKK'nın 7. maddesinde öngörülen şartlar çerçevesinde kişisel verilerin
      silinmesini veya yok edilmesini isteme,
    </li>
    <li>
      Yukarıdaki iki bent uyarınca yapılan işlemlerin, kişisel verilerin
      aktarıldığı üçüncü kişilere bildirilmesini isteme,
    </li>
    <li>
      İşlenen verilerin münhasıran otomatik sistemler vasıtasıyla analiz
      edilmesi suretiyle kişinin kendisi aleyhine bir sonucun ortaya çıkmasına
      itiraz etme,
    </li>
    <li>
      Kanuna aykırı olarak işlenmesi sebebiyle zarara uğraması hâlinde zararın
      giderilmesini talep etme haklarına sahiptir.
    </li>
  </ul>
  <p>
    Sistemde bir hesabınız varsa, bu haklarınızı kullanmak için <strong
      >sistemde kayıtlı e-posta adresiniz üzerinden</strong
    > <a href="mailto:yasal@kepce.org">yasal@kepce.org</a> adresine başvurabilirsiniz.
    Hesap güvenliği gereği, mevcut hesaplara yönelik taleplerde yalnızca sistemle
    eşleşen e-posta adresleri işleme alınır.
  </p>
  <p>
    Kişisel verilerinizle ilgili KVKK kapsamındaki bu haklarınızı kullanmak ve
    taleplerinizi iletmek için, başvurularınızı yasal süre olan 30 gün
    içerisinde ücretsiz olarak sonuçlandırmak üzere <a
      href="mailto:yasal@kepce.org">yasal@kepce.org</a
    >
    adresi üzerinden bizimle iletişime geçebilirsiniz.
  </p>
  <p>
    Bunun haricinde, KVKK süreçlerinden bağımsız olarak 5651 sayılı Kanun
    kapsamında sistemde yer alan bir içeriğin kişilik haklarınızı ihlal
    ettiğini düşünüyorsanız, Uyar-Kaldır prensibi çerçevesinde ihlale konu
    bağlantı (URL) ve gerekçeniz ile birlikte aynı e-posta adresinden içerik
    kaldırma bildiriminde bulunabilirsiniz. 5651 sayılı Kanun Madde 9
    uyarınca, kullanıcılar tarafından oluşturulan bir içerikten şikâyetçi
    olmanız durumunda ilgili içerik sağlayıcıya (içeriği oluşturan
    kullanıcıya) doğrudan ulaşma imkânınız bulunmuyorsa, Kepçe yer sağlayıcı
    sıfatıyla bildiriminizi değerlendirmekle yükümlüdür.
  </p>
</section>

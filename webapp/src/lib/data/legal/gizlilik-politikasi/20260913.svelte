<p>
  Gizlilik Politikamızı, 6698 sayılı Kişisel Verilerin Korunması Kanunu (KVKK)
  ve ilgili mevzuat kapsamındaki gereklilikler çerçevesinde, Kepçe (kepce.org)
  internet sitesi ve ilgili hizmetlerimize erişirken sağlayacağınız kişisel
  verilerinizin korunması hakkında sizi aydınlatmak amacıyla hazırladık.
</p>

<section>
  <h2>1. Veri Sorumlusu</h2>
  <p>
    6698 sayılı KVKK kapsamında veri sorumlusu, Kazım Geleş tarafından bireysel
    olarak geliştirilen ve işletilen Kepçe Projesi'dir. Resmî tebligat veya
    Uyar-Kaldır bildirimleri için
    <a href="/iletisim" data-link>iletişim sayfamız</a> veya
    <a href="mailto:yasal@kepce.org">yasal@kepce.org</a> e-posta adresimiz
    üzerinden bizimle irtibat kurabilirsiniz.
  </p>
</section>

<section>
  <h2>2. Toplanan Kişisel Veriler ve İşlenme Amaçları</h2>
  <p>
    Kepçe, ticari kâr veya davranışsal reklam hedeflemesi amacı gütmeyen açık
    kaynaklı bir organizasyon modeliyle çalışır. Toplanan veriler, yalnızca
    kullanıcı faydası gözetilerek asgari oranda işlenmekte olup aşağıdaki
    kategorilere ayrılır:
  </p>
  <ul>
    <li>
      <strong>Ziyaretçi Verileri:</strong> Sisteme herhangi bir hesaba giriş
      yapmaksızın erişmeniz durumunda işlem tarihi, saati, IP adresi ve port
      bilgisi, görüntülenen sayfalar, tarayıcı/cihaz modeliniz (User-Agent) ile
      <strong>IP adresiniz üzerinden otomatik tespit edilen yaklaşık konum (şehir)
      bilginiz</strong> elde edilmektedir. Bu bilgiler, yasal yükümlülüklerin
      yerine getirilmesinin yanı sıra size doğrudan doğru şehre ait menüyü sunmak
      amacıyla anlık olarak işlenir.
    </li>
    <li>
      <strong>Kullanıcı Etkileşim Verileri:</strong> Uygulama üzerinden hesaba
      giriş yapılarak gerçekleştirilen günlük yemek oylamaları, tabldot yorumları
      ve serbest yorumlar sistemimize kaydedilir.
    </li>
    <li>
      <strong>Hesap ve Kimlik Verileri:</strong> Giriş yaparken veya kayıt olurken
      doğrudan paylaştığınız kullanıcı kimliği, e-posta adresi ve tercih edilen
      giriş platformu (Google vb.) kayıtları.
    </li>
    <li>
      <strong>Aktif Oturum Verileri:</strong> Hesabınıza giriş yapıldığında hesap
      güvenliğinin temini, yetkisiz girişlerin tespit edilmesi ve aktif oturumlarınızı
      dilediğiniz an sonlandırabilmeniz amacıyla <strong>giriş yapılan IP adresi,
      giriş tarihi ve tarayıcı (User-Agent)</strong> bilgileriniz veri tabanımızda
      saklanır.
    </li>
  </ul>
  <p>
    Bu veriler, platform güvenliğinin temini, teknik hizmet kalitesinin sürdürülmesi,
    5651 sayılı Kanun kapsamındaki yasal kayıtların tutulması ve KVKK kapsamındaki
    başvuruların sonuçlandırılması amacıyla işlenmektedir. Kepçe, veri satışından
    veya hedefli reklamcılıktan hiçbir gelir elde etmez.
  </p>
</section>

<section>
  <h2>3. Kişisel Verilerin Toplanma Yöntemi ve Hukuki Sebepleri</h2>
  <p>
    Kişisel verileriniz, web sitesi ve mobil arayüzlerimizi ziyaretiniz sırasında
    tamamen veya kısmen otomatik yöntemlerle toplanmaktadır. Bu veriler, KVKK'nin
    5. maddesinin 2. fıkrasında düzenlenen aşağıdaki hukuki sebeplere dayalı olarak
    işlenir:
  </p>
  <ul>
    <li>
      <strong>Kanunlarda açıkça öngörülmesi (m. 5/2-a):</strong> 5651 sayılı
      Kanun m. 5/3 uyarınca yer sağlayıcıların trafik bilgilerini saklama
      zorunluluğu.
    </li>
    <li>
      <strong>Bir sözleşmenin kurulması veya ifasıyla doğrudan doğruya ilgili
      olması (m. 5/2-c):</strong> Kullanım Koşulları kapsamında kullanıcı hesabının
      açılması, oturum yönetiminin sağlanması ve kullanıcı etkileşimlerinin
      sunulabilmesi.
    </li>
    <li>
      <strong>Veri sorumlusunun hukuki yükümlülüğünü yerine getirebilmesi için
      zorunlu olması (m. 5/2-ç):</strong> Yetkili adli mercilerden gelebilecek yasal
      bilgi ve belge taleplerinin karşılanması.
    </li>
    <li>
      <strong>Veri sorumlusunun meşru menfaatleri için veri işlenmesinin zorunlu
      olması (m. 5/2-f):</strong> İlgili kişinin temel hak ve özgürlüklerine zarar
      vermemek kaydıyla platform güvenliğinin sağlanması, yetkisiz erişimlerin ve
      bot saldırılarının önlenmesi, rate limit uygulanması ve teknik hata izleme
      faaliyetlerinin yürütülmesi.
    </li>
  </ul>
</section>

<section>
  <h2>4. Kişisel Verilerin Aktarılması ve Yurt Dışı Sunucuları</h2>
  <p>
    Kişisel verileriniz ticari veya pazarlama amaçlarıyla üçüncü şahıslara
    satılmaz ya da aktarılmaz. Yalnızca yetkili adli ve idari mercilerden
    (Mahkemeler, Savcılıklar, Bilgi Teknolojileri ve İletişim Kurumu vb.) gelen
    usulüne uygun resmi talepler doğrultusunda yasal zorunluluk gereği ilgili
    makamlara bilgi verilebilir.
  </p>
  <p>
    Kepçe projesinin kullandığı bulut sunucular yurt dışında (Fransa/Marsilya -
    Oracle Cloud) bulunmaktadır. 6698 sayılı KVKK'nin 7499 sayılı Kanun ile
    yeniden düzenlenen 9. maddesi hükümleri uyarınca, verilerinizin yurt dışındaki
    bu sunucularda barındırılması işlemi, altyapı sağlayıcımız ile yapılan
    standart sözleşmeler ve teknik-idari veri güvenliği taahhütlerine (KVKK m. 9/4-c)
    dayalı olarak gerçekleştirilmektedir. Kayıtlı kullanıcılar bakımından bu işlem
    aynı zamanda kullanıcı sözleşmesinin ifası (KVKK m. 9/6-b) niteliğindedir.
  </p>
</section>

<section>
  <h2>5. 5651 Sayılı Kanun Kapsamında Saklama Süreleri</h2>
  <p>
    5651 sayılı Kanun kapsamında "Yer Sağlayıcı" olarak faaliyet göstermekteyiz.
    Bu kanun uyarınca sisteme erişen kullanıcılara ait işlem tarihi, saati, IP
    adresi ve port bilgisi gibi trafik verileri yasal zorunluluk gereği <strong>1
    yıldan az ve 2 yıldan fazla olmamak üzere</strong> saklanmaktadır.
  </p>
  <p>
    Kullanıcı hesapları ve bu hesaplar üzerinden oluşturulan içerikler (yorumlar,
    oylamalar vb.), kullanıcı hesabını sildiğinde veya yasal başvuru üzerine içerik
    kaldırıldığında KVKK Madde 7 gereği derhal kalıcı olarak silinir, yok edilir
    veya anonimleştirilir.
  </p>
</section>

<section>
  <h2>6. Tarayıcı Depolama ve Üçüncü Taraf Hizmetleri</h2>
  <p>
    Platformun temel işlevlerinin çalışabilmesi, şehir tercihinizin hatırlanması,
    tema seçiminiz ve oturum güvenliğinizin korunabilmesi amacıyla zorunlu
    çerezler (essential cookies) ile tarayıcınızın Local Storage ve Session Storage
    alanlarından yararlanılır.
  </p>
  <p>
    Platformumuzun hata takibi ve anonim analiz süreçlerinde üçüncü taraf teknik
    altyapı sağlayıcılarından yararlanılmaktadır. Bu kapsamda uygulamadaki yazılımsal
    hataları ve performans darboğazlarını tespit etmek amacıyla <strong>Sentry</strong>,
    çerezsiz ve tamamen anonim ziyaret istatistiklerini derlemek amacıyla
    <strong>Umami</strong> kullanılabilmektedir. İsteğe bağlı kimlik doğrulama için
    <strong>Google Auth</strong> servisinden yararlanılabilir. Bu servislerin veri
    işleme prensipleri hakkında ilgili sağlayıcıların kendi gizlilik politikalarını
    inceleyebilirsiniz.
  </p>
</section>

<section>
  <h2>7. Yaş Sınırı Beyanı</h2>
  <p>
    Kepçe'nin temel hedef kitlesi üniversite öğrencileri olmakla birlikte, 18
    yaşının altındaki bireylerin platformda hesap oluşturması ve kişisel verilerini
    paylaşması yasal temsilcilerinin (veli/vasi) onayına tabidir. 18 yaşın altındaki
    bir kullanıcının yasal temsilcisinin rızası olmaksızın kişisel verilerini
    paylaştığının bildirilmesi durumunda, bu veriler KVKK gereği derhal imha
    edilir. Reşit olmayan kullanıcıların sistemi yasal temsilcilerinin gözetimiyle
    kullanması kendi sorumluluklarındadır.
  </p>
</section>

<section>
  <h2>8. İlgili Kişinin Hakları ve Otomatik Karar Alma Beyanı</h2>
  <p>6698 sayılı KVKK'nin 11. maddesi uyarınca kişisel veri sahipleri:</p>
  <ul>
    <li>Kişisel veri işlenip işlenmediğini öğrenme,</li>
    <li>Kişisel verileri işlenmişse buna ilişkin bilgi talep etme,</li>
    <li>
      Kişisel verilerin işlenme amacını ve bunların amacına uygun kullanılıp
      kullanılmadığını öğrenme,
    </li>
    <li>
      Yurt içinde veya yurt dışında kişisel verilerin aktarıldığı üçüncü kişileri
      bilme,
    </li>
    <li>
      Kişisel verilerin eksik veya yanlış işlenmiş olması hâlinde bunların
      düzeltilmesini isteme,
    </li>
    <li>
      KVKK'nin 7. maddesinde öngörülen şartlar çerçevesinde kişisel verilerin
      silinmesini veya yok edilmesini isteme,
    </li>
    <li>
      Düzeltme, silme ve yok edilme işlemlerinin, kişisel verilerin aktarıldığı
      üçüncü kişilere bildirilmesini isteme,
    </li>
    <li>
      <strong>İşlenen verilerin münhasıran otomatik sistemler vasıtasıyla analiz
      edilmesi suretiyle kişinin kendisi aleyhine bir sonucun ortaya çıkmasına
      itiraz etme:</strong> Kepçe bünyesinde kullanıcılar hakkında davranışsal
      profil çıkarma, otomatik skorlama veya kullanıcı aleyhine hukuki ya da
      kişisel sonuç doğuracak hiçbir otomatik karar alma sistemi veya algoritması
      işletilmemektedir.
    </li>
    <li>
      Kişisel verilerin kanuna aykırı olarak işlenmesi sebebiyle zarara uğraması
      hâlinde zararın giderilmesini talep etme haklarına sahiptir.
    </li>
  </ul>
  <p>
    Veri Sorumlusuna Başvuru Usul ve Esasları Hakkında Tebliğ hükümleri uyarınca,
    KVKK kapsamındaki haklarınızı kullanmak için taleplerinizi sistemde kayıtlı
    e-posta adresiniz üzerinden <a href="mailto:yasal@kepce.org">yasal@kepce.org</a>
    adresine iletebilirsiniz. Başvurunuzda ad, soyad, talep konusu ve kimlik
    doğrulayıcı bilgilerin yer alması zorunludur. Başvurularınız yasal süre olan
    en geç 30 gün içerisinde ücretsiz olarak sonuçlandırılır.
  </p>

<p>
  Kepçe'yi kullanırken gizliliğinin nasıl korunduğunu, hangi özelliği sunabilmek için hangi verilere
  ihtiyaç duyduğumuzu ve bu verilerin başına ne geldiğini açık ve dürüst bir dille anlatmak istedik.
  Bu metin aynı zamanda 6698 sayılı Kişisel Verilerin Korunması Kanunu kapsamındaki aydınlatma
  bildirimimizdir.
</p>


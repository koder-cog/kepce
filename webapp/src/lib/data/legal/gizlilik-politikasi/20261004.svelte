</section>

<section>
  <h2>2. Hangi Özellik İçin Hangi Veriyi Alıyoruz?</h2>
  <p>
    Kepçe'de veri satışı, ticari kâr amacıyla davranışsal reklam hedeflemesi veya kullanıcı profili
    çıkarma gibi faaliyetler yoktur. Ne topluyorsak yalnızca platformun özelliklerini sorunsuz
    çalıştırmak için topluyoruz:
  </p>
  <ul>
    <li>
      <strong>Doğru Menüyü Karşına Getirmek İçin:</strong> Siteye girdiğinde seni doğrudan kendi şehrinin
      menüsüne yönlendirebilmek amacıyla IP adresinden yaklaşık şehir bilgini anlık olarak sunucu belleğinde
      tespit ederiz. Bu bilgi bellekte geçici olarak işlenir, diske kaydedilmez ve hiçbir şekilde loglanmaz.
      Açık kamu menülerini inceleyen anonim ziyaretçilerden hiçbir kişisel veri toplanmaz ve trafik kaydı
      tutulmaz.
    </li>
    <li>
      <strong>Oylama, Yorum ve Menü Paylaşımı (5651 Trafik Kayıtları):</strong> Günlük tabldot yemeklerini
      oylamak, yorum yazmak veya yemekhane menü fotoğrafı yüklemek istediğinde hesap açman gerekir. Kullanıcı
      adı, e-posta adresi ve Google kimlik belirtecinin yanı sıra 5651 sayılı Kanun m. 5/3 uyarınca yer
      sağlayıcı olarak içerik üreten kullanıcılara ait IP adresi, port bilgisi, işlem tarihi ve tarayıcı
      bilgisi gibi yasal trafik kayıtlarını tutmakla yükümlüyüz.
    </li>
    <li>
      <strong>Hesabını Güvende Tutmak İçin:</strong> Hesabına yetkisiz girişleri önlemek, bot saldırılarını
      engellemek ve açık olan oturumlarını görüp istediğin an kapatabilmen için giriş yapılan IP adresini,
      son işlem tarihini ve tarayıcıya ait User-Agent bilgisini saklarız.
    </li>
    <li>
      <strong>Menü Paylaşabilmen İçin:</strong> Yemekhane panosu veya menü fotoğrafı yüklediğinde bu görseli
      listeyi doğrulamak ve sisteme aktarmak için işleriz. Yayımlanan menüde kimlik bilgilerin yer almaz.
    </li>
  </ul>
</section>

<section>
  <h2>3. Verileri Hangi Hukuki Sebeplerle İşliyoruz?</h2>
  <p>
    Kişisel verilerini 6698 sayılı Kanunun 5. maddesinde belirtilen şu hukuki sebepler doğrultusunda
    işliyoruz:
  </p>
  <ul>
    <li>
      <strong>Kanunlarda açıkça öngörülmesi:</strong> Kanunun 5/2-a maddesi ve 5651 sayılı Kanun m. 5/3
      uyarınca yer sağlayıcı olarak yalnızca içerik üreten (yorum, oy, fotoğraf yükleme) kayıtlı kullanıcılara
      ait yasal trafik kayıtlarını tutma zorunluluğumuz.
    </li>
    <li>
      <strong>Sözleşmenin kurulması ve ifası:</strong> Kanunun 5/2-c maddesi uyarınca Kullanım Koşulları
      sözleşmesinin işletilmesi, hesabının açılması, oturumunun yönetilmesi, oylama ve yorum özelliklerinden
      faydalanabilmen.
    </li>
    <li>
      <strong>Hukuki yükümlülük:</strong> Kanunun 5/2-ç maddesi gereğince yetkili adli mercilerden gelebilecek
      yasal bilgi taleplerinin karşılanması.
    </li>
    <li>
      <strong>Meşru menfaatlerimiz:</strong> Kanunun 5/2-f maddesi uyarınca temel haklarına zarar vermemek
      kaydıyla platform güvenliğini sağlamak, bot saldırılarını önlemek, istek ve hız sınırlandırması
      uygulamak ve teknik hataları gidermek.
    </li>
  </ul>
</section>

<section>
  <h2>4. Sunucularımız Nerede ve Veriler Kimlerle Paylaşılır?</h2>
  <p>
    Kişisel verilerini ticari amaçlarla üçüncü şahıslara veya reklamcılara satmıyoruz. Yalnızca
    mahkeme veya savcılık gibi yetkili adli mercilerden usulüne uygun resmî bir talep geldiğinde
    yasal zorunluluk gereği ilgili makamlarla bilgi paylaşılabilir.
  </p>
  <p>
    Kepçe'nin ana amacı kamuya açık yemekhane menülerini herkes için şeffaf ve erişilebilir
    kılmaktır. Sitedeki açık menü verilerini inceleyen ziyaretçilerden hiçbir kişisel veri
    toplanmaz, IP logu tutulmaz ve yurt dışına herhangi bir veri aktarımı yapılmaz.
  </p>
  <p>
    Oylama, yorum yazma veya menü yükleme amacıyla hesap oluşturan kullanıcıların verileri ise
    Oracle Cloud altyapısı bünyesinde Fransa - Marsilya lokasyonundaki veri merkezlerinde
    barındırılır. 6698 sayılı Kanunun 9. maddesi uyarınca bu barındırma faaliyeti, kullanıcının
    kayıt aşamasında muhtemel riskler hakkında bilgilendirilerek verdiği açık rızası ve Kullanım
    Koşulları sözleşmesinin ifası kapsamında hizmetin teknik olarak sunulabilmesi amacıyla
    yürütülür.
  </p>
  <p>
    Kişisel verilerinin bu sunucularda barındırılmasını istemeyen kullanıcılar, hesaplarını
    diledikleri an silebilir ya da üye olmadan tüm kamu menü arşivinden anonim olarak
    faydalanabilir.
  </p>
</section>

<section>
  <h2>5. Verilerin Ne Kadar Süre Saklanır ve Ne Zaman Silinir?</h2>
  <p>
    Kişisel verilerin korunmasında ölçülülük ve amaca uygun saklama ilkeleri gereğince verilerin
    için aşağıdaki takvim uygulanır:
  </p>
  <ul>
    <li>
      <strong>Trafik verileri ve silinen içerikler:</strong> 5651 sayılı Kanun m. 5/3 uyarınca
      içerik üreten kullanıcılara ait erişim trafik kayıtları ile kullanıcının kendi sildiği yorum
      ve içeriklere ait log kayıtları, yasal zorunluluk gereği
      <strong>bir yıldan az ve iki yıldan fazla olmamak üzere</strong> saklanır. Bu sürenin sonunda otomatik
      olarak kalıcı biçimde yok edilir. Kamuya açık menüleri okuyan anonim ziyaretçilere ait hiçbir trafik
      kaydı oluşturulmaz ve saklanmaz.
    </li>
    <li>
      <strong>İncelenmeyi bekleyen menü fotoğrafları:</strong> Gönderilen menü fotoğrafları otuz gün içinde
      incelenmediği takdirde sistemden otomatik olarak silinir.
    </li>
    <li>
      <strong>Reddedilen menü fotoğrafları:</strong> Uygun bulunmayan veya okunamayan gönderimler doksan
      gün sonra kalıcı olarak temizlenir.
    </li>
    <li>
      <strong>Onaylanan menü listeleri:</strong> Menü sisteme girilip yayımlandıktan sonra gönderen kişinin
      kimlik bilgileri listeyle eşleştirilmez.
    </li>
    <li>
      <strong>Hesap silme:</strong> Hesabını sildiğinde kişisel verilerin derhal kalıcı olarak silinir
      veya kimliğinle bağı bütünüyle koparılarak anonimleştirilir. 5651 sayılı Kanun kapsamındaki zorunlu
      trafik kayıtları kanuni süresince saklı tutulur.
    </li>
  </ul>
</section>

<section>
  <h2>6. Hesabını ve Verilerini Nasıl Silebilirsin?</h2>
  <p>
    Kişisel verilerin üzerindeki denetim hakkın esastır. Hesabını ve verilerini dilediğin an
    silebilirsin:
  </p>
  <ul>
    <li>
      <strong>Profil ayarlarından silme:</strong> Giriş yapmış durumdayken hesap profil ayarlarından tek
      bir dokunuşla hesabını ve ilişkili kişisel verilerini kalıcı olarak silebilirsin.
    </li>
    <li>
      <strong>E-posta ile talep etme:</strong> Hesabına erişemiyorsan veya oturum açmakta sorun
      yaşıyorsan sistemde kayıtlı e-posta adresinden
      <a href="mailto:yasal@kepce.org">yasal@kepce.org</a> adresine yazarak hesabının ve tüm verilerinin
      silinmesini talep edebilirsin. Talebin incelenerek derhal işleme alınır.
    </li>
  </ul>
  <p>
    Hesap silme işlemi kalıcıdır. Silme işlemi tamamlandığında kişisel verilerin sistemden tamamen
    silinir veya kimliğinle bağı geri döndürülemez biçimde koparılır.
  </p>
</section>

<section>
  <h2>7. Çerezler ve Güvenlik Altyapımız</h2>
  <p>
    Sitenin temel işlevlerini yürütebilmek için tarayıcında sadece gerekli teknik ögeleri tutuyoruz:
  </p>
  <ul>
    <li>
      <strong>Oturum çerezi:</strong> Giriş yaptığında oturumunu doğrulamak için kullanılan kepce_token
      adlı teknik çerez, tarayıcı betiklerinin erişemediği HttpOnly ve güvenli SameSite korumalıdır.
    </li>
    <li>
      <strong>Tercih verileri:</strong> Seçtiğin şehir, açık veya koyu tema modu ile filtre tercihlerin
      tarayıcının yerel depolama alanında tutulur ve sunucuya kimliğinle eşleştirilerek gönderilmez.
    </li>
  </ul>
  <p>Teknik altyapımızda gizlilik odaklı bağımsız servislerden destek alıyoruz:</p>
  <ul>
    <li>
      <strong>Umami:</strong> Çerez kullanmayan, kişisel veri toplamayan ve ziyaretçi davranışlarını izlemeyen
      açık kaynaklı anonim sayfa sayacıdır.
    </li>
    <li>
      <strong>Cloudflare:</strong> Dağıtık hizmet engelleme saldırılarını önlemek ve kötü niyetli botları
      filtrelemek için kullanılan ters vekil güvenlik kalkanıdır. Trafik anlık olarak filtrelenir ve kullanıcı
      veri tabanı Cloudflare üzerinde tutulmaz.
    </li>
    <li>
      <strong>Google Auth:</strong> Şifre hatırlamak zorunda kalmadan güvenli giriş yapabilmen için kullanılır.
      Yalnızca Google ile giriş yapmayı seçtiğin takdirde temel profil kimlik belirteci doğrulanır.
    </li>
  </ul>
</section>


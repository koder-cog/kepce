<section>
  <h2>1. Lisans Bilgisi</h2>
  <p>
    Kepçe'nin kaynak kodları, API mimarisi ve web sitesi bileşenleri Özgür
    Yazılım Vakfı'nın (FSF)
    <a
      href="https://www.gnu.org/licenses/agpl-3.0.tr.html#license-text"
      target="_blank"
      rel="noopener">AGPL v3 (GNU Affero General Public License)</a
    >
    lisansına tabidir. API ve web sitesi kodlarının kullanımı veya düzenlenmesi
    bu lisansın şartlarına uygun olarak yapılmalıdır. Yazılımı kopyalayabilir,
    değiştirebilir ve dağıtabilirsiniz, ancak yazılımı bir ağ üzerinden (SaaS
    gibi) kullanıma sunmanız durumunda yaptığınız tüm değişiklikleri aynı lisans
    altında açık kaynak olarak paylaşma yükümlülüğünüz bulunmaktadır.
  </p>
  <p>
    AGPL v3 lisansı yalnızca yazılımın kaynak kodlarını kapsar. Kepçe platformunda
    derlenen ve tasnif edilen veri tabanı mimarisi, Kepçe markası ve ayırt edici
    işaretler bu lisansın kapsamı dışındadır.
  </p>
</section>

<section>
  <h2>2. Yaş Sınırı ve Fiil Ehliyeti</h2>
  <p>
    Kepçe, öncelikli olarak üniversite öğrencilerine yönelik bir platform
    olup kamuya açık menü görüntüleme ve arşiv tarama hizmeti tüm kullanıcılara
    açıktır.
  </p>
  <p>
    Bununla birlikte, platformda hesap oluşturulması, kişisel verilerin paylaşılması
    veya yorum gibi kullanıcı içeriklerinin üretilmesi Türk Medeni Kanunu ve Türk
    Borçlar Kanunu uyarınca geçerli bir irade beyanı gerektirir. 18 yaşından küçük
    bireylerin sisteme kayıt olması ve kişisel verilerini paylaşması yasal
    temsilcilerinin (veli/vasi) iznine ve gözetimine bağlıdır. Güvenli internet
    kullanımı için
    <a href="http://www.guvenliweb.org.tr/" target="_blank" rel="noopener"
      >guvenliweb.org.tr</a
    > kaynaklarını incelemeniz tavsiye edilir.
  </p>
</section>

<section>
  <h2>3. Hizmet Tanımı ve Tanımlar</h2>
  <p>
    Kepçe, 5651 sayılı İnternet Ortamında Yapılan Yayınların Düzenlenmesi ve Bu
    Yayınlar Yoluyla İşlenen Suçlarla Mücadele Edilmesi Hakkında Kanun çerçevesinde
    <strong>"Yer Sağlayıcı"</strong> sıfatıyla teknik altyapı hizmeti sunmaktadır.
    Sistemde yer alan içeriklerin niteliği şu şekildedir:
  </p>
  <ul>
    <li>
      <strong>Menü Verileri:</strong> Kredi ve Yurtlar Genel Müdürlüğü (KYK'de
      sunulan yemek hizmetleri), üniversiteler ve ilgili kamu kurumları tarafından
      kamuya açık biçimde duyurulan günlük yemek listelerinden derlenmektedir.
      Kepçe, kamuya açık bu verilerin öğrencilere ve araştırmacılara düzenli,
      erişilebilir ve arşivlenebilir bir biçimde ulaştırılmasını sağlayan bağımsız
      bir açık veri projesidir.
    </li>
    <li>
      <strong>Yorumlar ve Kullanıcı Katkıları:</strong> Kullanıcılar (İçerik
      Sağlayıcılar) tarafından oluşturulur. Kepçe, 5651 sayılı Kanun m. 5/1 gereğince
      yer sağladığı kullanıcı içeriklerini önceden kontrol etmek, hukuka aykırılık
      araştırması yapmak veya editoryal süzgeçten geçirmekle yükümlü değildir.
      Sistemde içerikleri önceden denetleyen veya onaylayan bir editör ya da filtre
      bulunmamaktadır. Sunulan kullanıcı yorumlarının doğruluğu, hukuka uygunluğu
      veya tarafsızlığı konusunda hiçbir taahhüt verilmez.
    </li>
    <li>
      <strong>Bildirimler:</strong> Sistem güncellemeleri veya kullanıcı tercihleri
      doğrultusunda Kepçe tarafından iletilen bilgilendirme iletileridir.
    </li>
  </ul>
</section>

<section>
  <h2>4. Hukuka Aykırı İçerik ve Şikâyet (Uyar-Kaldır Mekanizması)</h2>
  <p>
    Kepçe, sunulan kullanıcı içeriklerinin hukuka uygunluğunu önceden denetleme
    yükümlülüğü taşımamaktadır (5651 sayılı Kanun m. 5/1). Bununla birlikte, 5651
    sayılı Kanun m. 5/2 uyarınca, yer sağlayıcı hukuka aykırı içerikten haberdar
    edilmesi hâlinde bu içeriği yayından çıkarmakla yükümlüdür.
  </p>
  <p>
    Kişilik haklarının ihlali, telif hakkı ihlali, hakaret, nefret söylemi veya
    diğer mevzuata aykırılık iddialarınızı içeren bildirimlerinizi doğrudan
    <a href="mailto:yasal@kepce.org">yasal@kepce.org</a> e-posta adresimize iletebilirsiniz.
  </p>
  <p>
    Bildirimin değerlendirmeye alınabilmesi için aşağıdaki unsurları içermesi gerekir:
  </p>
  <ul>
    <li>İhlale konu içeriğin platformdaki tam ve açık internet adresi (URL),</li>
    <li>İhlal edildiği iddia edilen hakkın veya mevzuat hükmünün somut açıklaması,</li>
    <li>Bildirimde bulunan kişinin adı, soyadı ve doğrulanabilir iletişim bilgileri.</li>
  </ul>
  <p>
    Usulüne uygun iletilen bildirimler gecikmeksizin incelenir ve hukuka aykırılık
    tespit edilen içerikler yayından kaldırılır.
  </p>
</section>

<section>
  <h2>5. API ve Geliştirici Kullanımı</h2>
  <p>
    Geliştiriciler, Kepçe API'sini kullanırken adil kullanım kurallarına ve
    belirlenmiş istek sınırlarına (rate limit) uymak zorundadır. Canlı sunucu
    kaynaklarının agresif yöntemlerle (izinsiz scraping, DDoS vb.) suistimal
    edilmesi durumunda erişim engelleme yetkisi saklıdır.
  </p>
  <p>
    API verisini kullanan üçüncü taraf uygulamaların, verinin Kepçe platformundan
    alındığına dair görünür bir atıfta bulunması ve <a href="https://kepce.org">kepce.org</a>
    adresine aktif bağlantı vermesi zorunludur.
  </p>
</section>

<section>
  <h2>6. Kullanıcı Sorumlulukları ve Müdahale</h2>
  <p>
    Sisteme zarar verecek bot kullanımı, oy manipülasyonu, yetkisiz veri madenciliği
    ve hukuka aykırı içerik yükleme girişimleri yasaktır. 5651 sayılı Kanun m. 4
    uyarınca İçerik Sağlayıcılar (kullanıcılar), sisteme girdikleri yorum ve
    içeriklerin cezai ve hukuki sorumluluğunu bizzat üstlenirler.
  </p>
  <p>
    Kullanım koşullarının ihlali durumunda ilgili kullanıcı hesabını askıya alma
    veya IP bazlı erişim kısıtlaması uygulama hakkı Kepçe'ye aittir.
  </p>
</section>

<section>
  <h2>7. Telif Hakları, Veri Tabanı ve Haksız Rekabet Koruması</h2>
  <p>
    Yazılım kaynak kodları AGPL v3 lisansı kapsamında özgür olmakla birlikte,
    Kepçe tarafından kamuya açık kaynaklardan derlenerek oluşturulan veri tabanı
    mimarisi, besin ve kalori eşleştirmeleri ile şehir ve tarih indeksleri 5846
    sayılı Fikir ve Sanat Eserleri Kanunu (FSEK) m. 6/11 kapsamında işlenme eser ve
    FSEK Ek Madde 8 kapsamında veri tabanı yapımcısı koruması altındadır.
  </p>
  <p>
    Kamu kurumlarının kamuya açık ham yemek listeleri telife konu değildir. Ancak
    Kepçe veri tabanının tamamının veya önemli bir kısmının izinsiz otomatik
    araçlarla çekilmesi (scraping), kopyalanması veya ticari bir ürün haline
    getirilerek topluma iletilmesi FSEK Ek Madde 8 ve 6102 sayılı Türk Ticaret
    Kanunu m. 55 haksız rekabet hükümleri uyarınca yasaktır. Kepçe markası ve
    ayırt edici işaretler 6769 sayılı Sınai Mülkiyet Kanunu kapsamında korunmaktadır.
  </p>
</section>

<section>
  <h2>8. Sorumluluk Reddi (Alerjen, Kalori, Diyet ve Menü Bilgileri)</h2>
  <p>
    Kepçe uygulamasındaki tüm menü, kalori, gramaj ve fiyat bilgileri kamu
    duyurularından ve açık kaynaklardan derlenmektedir. Yemekhanelerdeki son
    dakika menü değişiklikleri, nöbetçi yurt düzenlemeleri veya tedarik
    aksaklıkları Kepçe'nin etki alanı dışındadır.
  </p>
  <p>
    Resmî kurumlar yemeklerin alerjen (glüten, laktoz, kuruyemiş vb.) veya diyet
    (vegan, vejetaryen vb.) içeriklerini ilan etmemektedir. Uygulamada yer alan
    alerjen ve diyet etiketleri, yalnızca yemek isimlerinden yola çıkılarak genel
    geçer tariflere göre algoritmik ve tahmini olarak üretilmektedir, kesin doğruluk
    taahhüdü içermez. Yemekhanelerdeki gizli içerik kullanımları, anlık reçete
    farklılıkları veya çapraz bulaşma riskleri tarafımızca bilinemez.
  </p>
  <p>
    Bu nedenle gıda alerjisi, intoleransı veya tıbbi diyet hassasiyeti bulunan
    kullanıcıların herhangi bir yemeği tüketmeden önce yemekhane yetkilileriyle
    veya aşçıbaşıyla bizzat görüşerek içerik teyidi alması kendi sorumluluğundadır.
    6098 sayılı Türk Borçlar Kanunu m. 115 uyarınca ağır kusur halleri saklı kalmak
    kaydıyla, alerjen veya diyet tahminlerinin hatalı olmasından veya bu bilgilere
    dayanılarak yapılan tüketimlerden kaynaklanabilecek hiçbir sağlık sorunundan
    ya da zarardan Kepçe sorumlu tutulamaz. Uygulamayı kullanan herkes bu şartları
    peşinen kabul etmiş sayılır.
  </p>
</section>

<section>
  <h2>9. 5651 Sayılı Kanun, Trafik Kayıtları ve Sunucu Konumu</h2>
  <p>
    Kişisel verilerin işlenmesi hakkında ayrıntılı bilgi için
    <a href="/gizlilik-politikasi" data-link>Gizlilik Politikası</a> sayfamızı
    inceleyiniz. 5651 sayılı Kanun uyarınca Yer Sağlayıcı sıfatıyla, sisteme
    erişen kullanıcıların trafik bilgilerini (IP adresi, port bilgisi, zaman damgası
    vb.) yasal zorunluluk gereği 1 yıldan az ve 2 yıldan fazla olmamak üzere
    saklamaktayız. Bu kayıtlar yalnızca yetkili adli mercilerin usulüne uygun
    talebi üzerine kanuni prosedürler çerçevesinde paylaşılır. Yer sağlayıcıya
    ilişkin tanıtıcı bilgilere <a href="/iletisim" data-link>İletişim</a>
    sayfasından erişebilirsiniz.
  </p>
  <p>
    <strong>Sunucu konumu:</strong> Sistem altyapımız bulut sağlayıcımızın
    (Oracle Cloud) yurt dışındaki (Fransa/Marsilya) veri merkezinde barındırılmaktadır.
    Sisteme erişen ve veri ileten kullanıcılar, verilerin bu sunucularda saklandığını
    kabul eder. Hata izleme (Sentry), çerezsiz anonim analiz (Umami) ve kimlik
    doğrulama (Google Auth) gibi entegrasyonlar kullanıldığında, bu sağlayıcıların
    kendi gizlilik ve güvenlik kuralları da geçerlidir.
  </p>
</section>


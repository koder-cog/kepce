<section>
  <h2>7. Veri Ayrımı, Telif ve Marka Hakları</h2>
  <p>Kepçe platformundaki veriler ve haklar iki temel kategoriye ayrılır:</p>
  <ul>
    <li>
      <strong>Kamu verileri:</strong> Üniversiteler ve KYK yurtları gibi kamu kurumlarının duyurduğu ham
      yemek listeleri ile fiyat bilgileri kamuya aittir ve telife konu değildir ancak bu verilerin doğrudan
      Kepçe sunucularından, altyapısından veya servislerinden çekilmesinin bağlayıcı şartları vardır.
      Verilerin web sayfalarını otomatik yöntemlerle kontrolsüz kazımak yerine, platformun sunduğu API
      veya RSS gibi resmî kanallar üzerinden çekilmesi ve belirlenen istek sınırlarına uyulması zorunludur.
      Ayrıca Kepçe derlediği kamu verilerinde ilgili kurum ve kaynakları nasıl açıkça belirtiyorsa Kepçe
      altyapısını kullanan tarafların da verinin yer aldığı mecrada kepce.org adresine görünür şekilde
      atıf vermesi şarttır. Bu şartlara uymayan, sunucu kaynaklarını tüketen veya kontrolsüz veri çekenlerin
      erişimi derhal ve teknik olarak engellenir.
    </li>
    <li>
      <strong>Özgün Kepçe içerikleri:</strong> Kullanıcıların platforma yazdığı yorumlar, tabldot değerlendirmeleri,
      yüklenen yemek fotoğrafları, besin eşleştirmeleri ve arayüz tasarımları başta olmak üzere kamuya
      açık ham yemek listeleri haricinde platformda üretilen, işlenen ve tasnif edilen tüm özgün içerikler
      ile veri tabanı yapısı Kepçe platformuna ve topluluğuna aittir. Bu içeriklerin izinsiz otomatik
      araçlarla kazınması, kopyalanması, başka platformlarda kaynak gösterilmeden ticari ya da gayriticari
      amaçla kullanılması veya bir başkası tarafından kendi verisi gibi sunulması yasaktır. Bu tür eylemler
      5846 sayılı Fikir ve Sanat Eserleri Kanunu ile Türk Ticaret Kanunu m. 55 haksız rekabet hükümleri
      kapsamında ihlal oluşturur. Emek hırsızlığı ve haksız sahiplenme durumlarında hukuki ve cezai tüm
      yasal haklarımız kullanılır.
    </li>
  </ul>
  <p>
    <strong>Yazılım lisansı ve marka ayrımı:</strong> Kaynak kodlarımız AGPL v3 lisansıyla açık kaynak
    olmakla birlikte, AGPL v3 Madde 7/e uyarınca bu lisans projenin marka haklarını devretmez. "Kepçe"
    adı, kepce.org alan adı, proje logosu ve ayırt edici görsel kimlik ögeleri 6769 sayılı Sınai Mülkiyet
    Kanunu kapsamında korunur. Kodları çatallayarak bağımsız bir sunucuda çalıştıranlar, resmî logoyu
    ve ismi kaldırıp kendi özgün markalarını kullanmakla yükümlüdür. Üçüncü taraflar, yalnızca sistemlerinin
    Kepçe altyapısını veya API'sini kullandığını dürüstçe belirtmek koşuluyla teknik atıfta bulunabilir
    ancak resmî hizmet izlenimi uyandıramaz. Ayrıntılı kurallar için Marka Kullanım Politikamız esastır.
  </p>
</section>

<section>
  <h2>8. Menü, Fiyat ve Alerjen Bilgilerinde Sorumluluk Sınırı</h2>
  <p>
    Kepçe'deki tüm menü, kalori, gramaj ve fiyat bilgileri kamu duyurularından derlenmektedir.
    Yemekhanelerdeki turnike ve fiş fiyatları ile fiziki panolardaki anlık duyurular esas olup
    platformdaki menü ve fiyat bilgileri resmî ve bağlayıcı bir taahhüt oluşturmaz. Yemekhanelerdeki
    son dakika menü değişiklikleri, nöbetçi yurt düzenlemeleri veya tedarik aksaklıkları Kepçe'nin
    kontrolü dışındadır.
  </p>
  <p>
    Resmî kurumlar yemeklerin glüten, laktoz veya kuru yemiş gibi alerjenler ile vegan ve vejetaryen
    gibi özel diyet içeriklerini ilan etmemektedir. Sitede yer alan alerjen ve diyet etiketleri,
    yalnızca yemek isimlerinden yola çıkılarak genel geçer tariflere göre algoritmik ve tahmini
    olarak üretilmektedir. Kesin bir doğruluk taahhüdü içermez. Yemekhanelerdeki gizli içerik
    kullanımları, anlık reçete farklılıkları veya çapraz bulaşma riskleri tarafımızca bilinemez.
  </p>
  <p>
    Bu nedenle gıda alerjisi, intoleransı veya tıbbi diyet hassasiyeti bulunan kullanıcıların
    herhangi bir yemeği tüketmeden önce yemekhane yetkilileriyle veya aşçıbaşıyla bizzat görüşerek
    içerik teyidi alması kendi sorumluluğundadır. 6098 sayılı Türk Borçlar Kanunu m. 115 uyarınca
    ağır kusur hâlleri saklı kalmak kaydıyla alerjen veya diyet tahminlerinin hatalı olmasından ya
    da bu bilgilere dayanılarak yapılan tüketimlerden kaynaklanabilecek hiçbir sağlık sorunundan
    veya zarardan Kepçe sorumlu tutulamaz. Kepçe'yi kullanan herkes bu şartları peşinen kabul etmiş
    sayılır.
  </p>
</section>

<section>
  <h2>9. 5651 Sayılı Kanun, Trafik Kayıtları ve Sunucu Konumu</h2>
  <p>
    Kişisel verilerin işlenmesi hakkında ayrıntılı bilgi için
    <a href="/gizlilik-politikasi" data-link>Gizlilik Politikası</a> sayfamızı inceleyebilirsin. 5651
    sayılı Kanun uyarınca Yer Sağlayıcı sıfatıyla sisteme erişen kullanıcılara ait IP adresi, port bilgisi
    ve zaman damgası gibi yasal trafik kayıtlarını bir yıldan az ve iki yıldan fazla olmamak üzere saklamaktayız.
    Bu kayıtlar yalnızca yetkili adli mercilerin usulüne uygun talebi üzerine kanuni prosedürler çerçevesinde
    paylaşılır.
  </p>
  <p>
    <strong>Sunucu konumu:</strong> Sistem altyapımız Oracle Cloud bünyesinde Fransa'nın Marsilya şehrinde
    bulunan veri merkezinde barındırılmaktadır. Sisteme erişen ve veri ileten kullanıcılar, verilerin
    bu sunucularda saklandığını kabul eder. Çerezsiz anonim analiz için Umami, güvenli kimlik doğrulama
    için Google ve kötü niyetli botları filtrelemek için Cloudflare gibi harici sağlayıcılar kullanıldığında
    bu servislerin kendi gizlilik kuralları da geçerlidir.
  </p>
</section>


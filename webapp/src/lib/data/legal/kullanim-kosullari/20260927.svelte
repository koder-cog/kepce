<section>
  <h2>2. Yaş ve Kullanım Ehliyeti</h2>
  <p>Kepçe'deki kamuya açık yemek listelerini ve arşivleri incelemek herkese açıktır.</p>
  <p>
    Kepçe öncelikli olarak üniversite öğrencilerine hitap eder. On sekiz yaşından küçük bireylerin
    platformu veli veya yasal temsilcilerinin bilgisi ve gözetimi dahilinde kullanması tavsiye
    edilir. Sisteme sağlanan bilgilerin doğruluğundan ve hesap kullanımından doğan sorumluluk bizzat
    kullanıcıya aittir. Reşit olmayan bir bireyin platformu izinsiz kullandığına yönelik haklı bir
    bildirim almamız hâlinde ilgili hesabı ve içerikleri kaldırma hakkımız saklıdır.
  </p>
  <p>
    Platformda hesap açan, oylamalara katılan veya yorum yazan herkes bu şartları kabul etmiş
    sayılır. Güvenli internet kullanımı için
    <a href="http://www.guvenliweb.org.tr/" target="_blank" rel="noopener">guvenliweb.org.tr</a> kaynaklarını
    incelemeni öneririz.
  </p>
</section>

<section>
  <h2>3. Yer Sağlayıcı Olarak Sorumluluğumuz</h2>
  <p>
    Kepçe, 5651 sayılı İnternet Kanunu kapsamında <strong>Yer Sağlayıcı</strong>
    sıfatıyla teknik altyapı hizmeti sunmaktadır. Sistemdeki içeriklerin niteliği şöyledir:
  </p>
  <ul>
    <li>
      <strong>Menü Verileri:</strong> Kredi ve Yurtlar Genel Müdürlüğüne bağlı yurtlar, üniversiteler,
      ilgili kamu duyuruları ve dijital açık kaynak derlemelerinden toplanmaktadır. Şeffaflık ilkemiz
      gereği verinin alındığı kaynak menü kartlarında açıkça belirtilir. Kepçe, bu kamu verilerini öğrenciler
      ve araştırmacılar için düzenli, erişilebilir ve arşivlenebilir kılan bağımsız bir açık veri platformudur.
    </li>
    <li>
      <strong>Kullanıcı Yüklemeleri:</strong> Menü paylaşımı amacıyla sisteme yüklediğin pano fotoğrafları
      ve belgeler, yemek listelerinin dijitalleştirilmesi amacıyla işlenir. Yüklenen fotoğrafların üçüncü
      şahısların yüzleri veya kişisel verilerini içermemesi, yalnızca menü içeriğine odaklanması gerekir.
      Yüklediğin belgenin Kepçe tarafından okunmasını, kırpılmasını, metne dönüştürülerek kamuya açık
      yemek arşivine eklenmesini kabul etmiş sayılırsın.
    </li>
    <li>
      <strong>Kullanıcı Yorumları ve Oylar:</strong> Kanun kapsamında içerik sağlayıcı sayılan kullanıcılar
      tarafından üretilir. 5651 sayılı Kanun m. 5/1 gereğince yer sağlayıcı olarak sunulan kullanıcı içeriklerini
      önceden denetleme, editöryal süzgeçten geçirme veya doğruluk araştırması yapma yükümlülüğümüz yoktur.
      Yorumların doğruluğu veya hukuka uygunluğu konusunda hiçbir taahhüt verilmez.
    </li>
    <li>
      <strong>Bildirimler:</strong> Sistem güncellemeleri veya kullanıcı tercihleri doğrultusunda iletilen
      bilgilendirme iletileridir.
    </li>
  </ul>
</section>

<section>
  <h2>4. Hukuka Aykırı İçerik ve Uyar-Kaldır Bildirimleri</h2>
  <p>
    Kullanıcı içeriklerini önceden denetleme yükümlülüğümüz bulunmamakla birlikte 5651 sayılı Kanun
    m. 5/2 uyarınca hukuka aykırı bir içerikten haberdar edildiğimizde bu içeriği gecikmeksizin
    yayından kaldırmakla yükümlüyüz.
  </p>
  <p>
    Kişilik haklarının ihlali, telif ihlali, hakaret veya diğer mevzuata aykırılık iddialarını
    içeren bildirimlerini doğrudan
    <a href="mailto:yasal@kepce.org">yasal@kepce.org</a> e-posta adresimize iletebilirsin.
  </p>
  <p>Bildiriminin değerlendirmeye alınabilmesi için şu unsurları içermesi gerekir:</p>
  <ul>
    <li>İhlale konu içeriğin platformdaki tam ve açık internet bağlantısı,</li>
    <li>İhlal edildiği iddia edilen hakkın veya mevzuat hükmünün somut açıklaması,</li>
    <li>Bildirimde bulunan kişinin adı, soyadı ve doğrulanabilir iletişim bilgileri.</li>
  </ul>
  <p>
    Usulüne uygun iletilen bildirimler incelenir ve hukuka aykırılık tespit edilen içerikler
    yayından çıkarılır. İletilen şikâyet ve bildirimler kişisel haberleşme sayılmaz. Hukuki
    inceleme, hak sahipliği teyidi ve yasal prosedürlerin yürütülmesi amacıyla gerekli görüldüğü
    takdirde ilgili taraflarla ve yetkili adli mercilerle paylaşılabilir.
  </p>
</section>

<section>
  <h2>5. API ve Adil Kullanım Sınırları</h2>
  <p>
    Geliştiricilerin Kepçe API'sini kullanmasından memnuniyet duyarız ancak canlı sunucularımızı
    yoracak agresif veri kazıma, bot akınları veya hizmeti engelleyici saldırılar yasaktır. Bu tür
    durumlarda erişim engelleme yetkimiz saklıdır.
  </p>
  <p>
    API verilerini kullanan üçüncü taraf uygulamaların verinin Kepçe platformundan alındığına dair
    görünür bir atıfta bulunması ve
    <a href="https://kepce.org">kepce.org</a> adresine aktif bağlantı vermesi zorunludur. Yapılacak alıntılar
    ve veri kullanımları, veri tabanımızın esaslı bir kısmını kapsayacak veya tam içeriğe ulaşmak için
    Kepçe'nin ziyaret edilmesi ihtiyacını ortadan kaldıracak boyutta olamaz.
  </p>
</section>

<section>

    çekilmesi (scraping) ve ticari amaçla yeniden yayımlanması yasaktır.
    Marka hakları ve verinin yapısal bütünlüğü saklıdır.
  </p>
</section>

<section>
  <h2>8. Sorumluluk Reddi</h2>
  <p>
    Kepçe uygulamasındaki tüm menü, kalori ve gramaj bilgileri dış
    kaynaklardan sağlanmakta olup, doğruluğu hiçbir şekilde garanti edilmez.
  </p>
  <p>
    Resmî kurumlar yemeklerin alerjen (glüten, laktoz, kuruyemiş vb.) veya
    diyet (vegan, vejetaryen vb.) içeriklerini paylaşmamaktadır.
    Uygulamamızda gördüğünüz alerjen ve diyet etiketleri, yalnızca yemek
    isimlerinden yola çıkılarak genel geçer tariflere göre tahmini olarak
    sunulmaktadır ve %100 doğruluk taşımaz. Yemekhanelerdeki gizli içerik
    kullanımları, anlık reçete değişiklikleri veya çapraz bulaşma riskleri
    tarafımızca bilinemez.
  </p>
  <p>
    Bu nedenle; gıda alerjisi, intoleransı veya tıbbi/diyet hassasiyeti olan
    kullanıcıların, herhangi bir yemeği tüketmeden önce mutlaka yemekhane
    personeliyle veya aşçıbaşıyla bizzat görüşerek içerik teyidi alması
    kendi sorumluluğundadır. Uygulamada yer alan alerjen/diyet etiketlerinin
    hatalı tahmin edilmesinden veya bu verilere güvenilerek yapılan
    tüketimlerden doğabilecek hiçbir sağlık probleminden veya mağduriyetten
    Kepçe sorumlu tutulamaz. Uygulamayı kullanan herkes bu riskleri ve
    şartları peşinen kabul etmiş sayılır.
  </p>
</section>


<section>
  <h2>2. Yaş Sınırı</h2>
  <p>
    Kepçe, öncelikli olarak üniversite öğrencilerine yönelik bir platform
    olup içeriği genel kullanıma açıktır. Ancak kullanıcılar tarafından
    oluşturulan içerikler (yorumlar, oylamalar vb.) tam olarak
    denetlenemediğinden, platformda zaman zaman yetişkinlere yönelik
    ifadeler yer alabilir. 18 yaşından küçük kullanıcıların platformu
    kullanabilmesi için yasal temsilcilerinin (veli/vasi) bilgisi ve onayı
    gereklidir. Güvenli internet kullanımı için
    <a href="http://www.guvenliweb.org.tr/" target="_blank" rel="noopener"
      >guvenliweb.org.tr</a
    > kaynaklarını incelemeniz tavsiye edilir.
  </p>
</section>

<section>
  <h2>3. Hizmet Tanımı ve Tanımlar</h2>
  <p>
    Kepçe, 5651 sayılı Kanun çerçevesinde <strong>"Yer Sağlayıcı"</strong> sıfatıyla
    hizmet sunmaktadır. Sistemdeki içeriklerin yayınlanma süreci şu şekildedir:
  </p>
  <ul>
    <li>
      <strong>Yorumlar:</strong> Kullanıcılar (İçerik Sağlayıcılar) tarafından
      oluşturulur. Kullanıcı deneyimini sabote edecek spam, bot saldırıları ve
      aleni küfürlere karşı otomatik bir filtreleme mekanizması (YZ) devrededir.
      Bu teknik filtreleme, Kepçe'nin 5651 sayılı Kanun kapsamındaki "Yer Sağlayıcı"
      statüsünü değiştirmez ve platforma editoryal bir sorumluluk yüklemez. Sisteme
      içerik seçen veya onaylayan bir editör bulunmamakta olup, sunulan içeriklerin
      doğruluğu veya uygunluğu konusunda hiçbir taahhüt verilmemektedir.
    </li>
    <li>
      <strong>Bildirimler:</strong> Kepçe tarafından kullanıcılara gönderilmektedir.
    </li>
  </ul>
</section>

<section>
  <h2>4. Hukuka Aykırı İçerik ve Şikayet (Uyar-Kaldır)</h2>
  <p>
    Kepçe, sunulan içeriklerin hukuka uygunluğunu önceden denetleme
    yükümlülüğü taşımamaktadır (5651 sayılı Kanun m. 5/1). Ancak 5651
    sayılı Kanun m. 5/2 uyarınca, yer sağlayıcı hukuka aykırı içerikten
    haberdar edilmesi hâlinde bu içeriği yayından çıkarmakla yükümlüdür.
    Hukuka aykırı olduğunu düşündüğünüz içerikleri şikayet butonları
    üzerinden bildirebilir veya ihtarname/resmî bildirimlerinizi doğrudan <a href="mailto:yasal@kepce.org">yasal@kepce.org</a>
    adresine iletebilirsiniz. Yapılan bildirimler titizlikle incelenir ve gerekli
    durumlarda yasal mercilerle paylaşılabilir.
  </p>
</section>

<section>
  <h2>5. API ve Geliştirici Kullanımı</h2>
  <p>
    Geliştiriciler, Kepçe API'sini tüketirken adil kullanım kurallarına ve
    belirlenmiş istek sınırlarına (rate limit) uymak zorundadır. Canlı
    sunucu kaynaklarının agresif yöntemlerle (scraping, DDoS vb.) suistimal
    edilmesi durumunda erişim engelleme yetkisi Kepçe'ye aittir. API
    verisini kullanan uygulamaların, verinin Kepçe platformundan alındığına
    dair bariz bir atıfta bulunması ve aktif link vermesi zorunludur.
  </p>
</section>

<section>
  <h2>6. Kullanıcı Sorumlulukları ve Müdahale</h2>
  <p>
    Sisteme zarar verecek bot kullanımı, oy manipülasyonu ve zararlı içerik
    yükleme girişimleri yasaktır. İçerik Sağlayıcılar (Kullanıcılar),
    paylaştıkları içeriklerin yasal sorumluluğunu bizzat üstlenirler.
    Kullanım koşullarının ihlali durumunda IP bazlı kısıtlama uygulama
    yetkisi Kepçe'nin hakkıdır.
  </p>
</section>


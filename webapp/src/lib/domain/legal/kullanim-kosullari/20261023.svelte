</section>

<section>
  <h2>8. Menü, Fiyat ve Alerjen Tahminlerinde Sorumluluk Sınırı (Önemli Uyarı)</h2>
  <p>
    Kepçe'nin yemekhanelerle, üniversitelerle, KYK ile veya malzeme tedarikçileriyle herhangi bir
    organik bağı, mutfak erişimi veya denetim yetkisi yoktur. Tüm menü, kalori, gramaj ve fiyat
    bilgileri kamu duyurularından derlenmekte olup yemekhanelerdeki turnike fiyatları ile fiziki
    panolardaki anlık duyurular esastır.
  </p>
  <p>
    <strong>Alerjen ve Diyet Etiketleri Hakkında Kesin Uyarı:</strong> Resmî kurumlar yemeklerin
    glüten, laktoz veya kuru yemiş gibi alerjenler ile vegan ve vejetaryen gibi özel diyet içeriklerini
    veya gerçek mutfak reçetelerini ilan etmemektedir. Sitede yer alan alerjen, çölyak ve diyet
    etiketleri, gerçek mutfak analizine <strong>dayanmamakta</strong>; yalnızca yemek isimlerinin
    otomatik kelime analiziyle eşleştirilmesinden ibaret olup bağlayıcı bir sağlık tavsiyesi teşkil
    etmez. Yemekhanelerdeki gizli içerik kullanımları, anlık reçete farklılıkları veya çapraz bulaşma
    riskleri tarafımızca bilinemez.
  </p>
  <p>
    Bu nedenle çölyak, gıda alerjisi, intoleransı veya tıbbi/özel diyet hassasiyeti bulunan
    kullanıcıların sitedeki otomatik etiketlere veya kullanıcı yorumlarına güvenerek hareket etmemesi;
    herhangi bir yemeği tüketmeden önce fiziki yemekhane personeliyle veya aşçıbaşıyla bizzat görüşerek
    içerik teyidi alması zorunludur. Bu açık uyarıya rağmen mutfak teyidi alınmaksızın yapılan
    tüketimlerde sorumluluk ve risk, TBK m. 52 (zarar görenin ortak kusuru), m. 63 ve m. 115 hükümleri
    çerçevesinde tamamen kullanıcıya aittir.
  </p>
</section>


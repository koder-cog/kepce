  <h2>7. Veri Ayrımı, Lisans ve Görsel Kimlik Hakları</h2>
  <ul>
    <li>
      <strong>Kamu verileri:</strong> Üniversiteler ve KYK yurtları gibi kamu kurumlarının duyurduğu ham
      yemek isimleri ile fiyat bilgileri kamuya aittir; ancak bu verilerin Kepçe altyapısından çekilmesi
      yalnızca resmî API/RSS kanalları üzerinden, belirlenen istek sınırlarına uyularak ve kaynak
      gösterilerek gerçekleştirilebilir.
    </li>
    <li>
      <strong>Veri tabanı mimarisi ve kullanıcı katkıları:</strong> Ham yemek listeleri haricinde
      platformda nitelik ve nicelik açısından esaslı bir emekle oluşturulan, doğrulanan ve tasnif
      edilen veri tabanı yapısı, besin eşleştirmeleri ve arayüz tasarımları FSEK m. 6/11, Ek Madde 8 ve
      6102 sayılı Türk Ticaret Kanunu (TTK) m. 54 vd. haksız rekabet hükümleri kapsamında korunmaktadır.
      Kullanıcı, platformda paylaştığı yorum ve fotoğraflar üzerinde Kepçe'ye dünya çapında geçerli,
      süresiz, bedelsiz ve gayriinhisari (münhasır olmayan) bir işleme, çoğaltma, yayma ve umuma iletim
      lisansı vermiş olduğunu kabul eder.
    </li>
  </ul>
  <p>

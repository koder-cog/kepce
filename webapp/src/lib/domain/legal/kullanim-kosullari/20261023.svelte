<section>
  <h2>2. Hizmetin Niteliği ve Hesap Güvenliği</h2>
  <p>
    Kepçe, üniversite ve KYK yemekhane menülerini kamuya açık kaynaklardan derleyen, kâr amacı gütmeyen,
    ücretsiz bir açık veri platformudur. Kamuya açık yemek listelerini incelemek herkese açıktır.
  </p>
  <p>
    Kepçe öncelikli olarak üniversite öğrencilerine hitap eder. On sekiz yaşından küçük bireylerin
    platformu veli veya yasal temsilcilerinin gözetimi dahilinde kullanması tavsiye edilir. Seçilen
    rumuzdan ve üretilen içeriklerden doğan sorumluluk bizzat kullanıcıya aittir. Hesaplar sıfır bilgi
    mimarisiyle korunduğundan ve açık e-posta adresi veri tabanında tutulmadığından,
    kullanıcının kaydolduğu e-posta adresini unutması hâlinde hesabın kurtarılması teknik olarak mümkün
    değildir.
  </p>
</section>

<section>
  <h2>3. 5651 Sayılı Kanun Kapsamında Hukuki Statü ve Sorumluluk</h2>
  <p>
    Kepçe, kamuya açık kaynaklardan derleyip sunduğu yemekhane menüleri bakımından 5651 sayılı Kanun
    m. 2/1-f ve m. 4 kapsamında <strong>İçerik Sağlayıcı</strong>dır. Kullanıcılar tarafından
    oluşturulan menü yorumları ve yemek fotoğrafları bakımından ise platform yalnızca ev sahipliği
    yapmakta olup sorumluluk rejimi şöyledir:
  </p>
  <ul>
    <li>
      <strong>Menü Verileri:</strong> Kredi ve Yurtlar Genel Müdürlüğüne bağlı yurtlar, üniversiteler,
      ilgili kamu duyuruları ve açık kaynak derlemelerinden toplanmaktadır. Verinin alındığı kaynak
      menü kartlarında açıkça belirtilir.
    </li>
    <li>
      <strong>Menü Panosu Gönderimleri:</strong> Menü listesinin dijitalleştirilmesi amacıyla gönderilen
      pano fotoğrafları sitede kamuya açık olarak yayımlanmaz (5651 sayılı Kanun m. 2/1-ğ anlamında
      yayın haline getirilmez); yalnızca metne dönüştürülerek yemek arşivine eklenir ve görsel imha
      edilir.
    </li>
    <li>
      <strong>Kullanıcı Yorumları ve Tepsi Fotoğrafları:</strong> 5651 sayılı Kanun m. 4/1 uyarınca
      yorum yazan veya fotoğraf yükleyen kullanıcılar, ürettikleri bu içerikler bakımından bizzat
      <strong>İçerik Sağlayıcı</strong> sıfatını haizdir ve sundukları her türlü içerikten doğrudan
      sorumludur. Yüklenen yemek/tepsi fotoğraflarında <strong>üçüncü şahısların yüzlerinin, özel
      hayatına ilişkin unsurların, öğrenci kimlik kartlarının veya yemekhane fişlerinin yer almaması</strong>,
      görselin yalnızca yemek tepsisine odaklanması zorunludur.
    </li>
    <li>
      <strong>Ön Denetim Yükümlülüğünün Bulunmaması:</strong> 5651 sayılı Kanun m. 5/1 gereğince
      kullanıcılar tarafından sunulan içerikleri önceden kontrol etme veya hukuka aykırı bir faaliyetin
      söz konusu olup olmadığını araştırma yükümlülüğümüz yoktur; hak ihlali bildirimlerinde
      "Uyar-Kaldır" prensibi işletilir.
    </li>
  </ul>
</section>

<section>
  <h2>4. Hukuka Aykırı İçerik ve Uyar-Kaldır Bildirimleri</h2>
  <p>
    5651 sayılı Kanun ve 5846 sayılı Fikir ve Sanat Eserleri Kanunu (FSEK) Ek Madde 4 uyarınca hukuka
    aykırı olduğu veya hak ihlali oluşturduğu bildirilen içerikler incelenerek yayından kaldırılır.
  </p>
  <p>
    Herhangi bir yorum veya fotoğraf için sitedeki <strong>"Bildir"</strong> butonunu kullanabilir ya da
    kişilik haklarının ihlali, üçüncü kişi görüntüsü/verisi paylaşımı, telif ihlali veya hakaret
    iddialarını içeren bildirimlerini doğrudan
    <a href="mailto:yasal@kepce.org">yasal@kepce.org</a> e-posta adresimize iletebilirsin.
  </p>
  <ul>
    <li>İhlale konu içeriğin platformdaki tam bağlantısı (URL) veya somut konumu,</li>
    <li>İhlal edildiği iddia edilen hakkın veya mevzuat hükmünün açıklaması,</li>
    <li>Bildirimde bulunan kişinin hak sahipliğini/ilgisini gösteren bilgi ve iletişim adresi</li>
  </ul>
  <p>
    yer almalıdır. Usulüne uygun iletilen bildirimler incelenir ve hukuka aykırılık tespit edilen
    içerikler derhal (FSEK Ek Madde 4 kapsamındaki taleplerde en geç üç gün içinde) yayından çıkarılır.
  </p>
</section>

<section>
  <h2>5. API, Veri Tabanı Koruması ve Adil Kullanım Sınırları</h2>
  <p>
    Geliştiricilerin Kepçe API'sini adil kullanım sınırları içinde kullanmasından memnuniyet duyarız;
    ancak canlı sunucularımızı yoracak agresif veri kazıma (scraping), bot akınları veya hizmeti
    engelleyici saldırılar yasaktır.
  </p>
  <p>
    API verilerini kullanan üçüncü taraf uygulamaların verinin Kepçe platformundan alındığına dair
    görünür bir atıfta bulunması ve <a href="https://kepce.org">kepce.org</a> adresine aktif bağlantı
    vermesi zorunludur. 5846 sayılı FSEK m. 6/11 ve Ek Madde 8 (Veri Tabanı Yapımcısının Sui Generis
    Hakları) uyarınca; Kepçe veri tabanının içeriğinin önemli bir kısmının veya tamamının izinsiz
    olarak otomatik araçlarla çekilmesi, kopyalanması veya Kepçe'nin ziyaret edilmesi ihtiyacını
    ortadan kaldıracak boyutta başka platformlarda yeniden yayımlanması hukuka aykırıdır.
  </p>
</section>

<section>
  <h2>6. Kullanıcı Kuralları ve Müdahale Yetkisi</h2>
  <p>
    Sisteme zarar verecek bot kullanımı, oylama ve bildirim manipülasyonu, küfür/hakaret, telefon
    numarası veya kimlik numarası paylaşımı, başka kişilerin izinsiz fotoğraflarını yükleme girişimleri
    yasaktır. Kural ihlali durumunda ilgili içeriği kaldırma, kullanıcı hesabını askıya alma veya
    teknik kısıtlama uygulama hakkımız saklıdır.
  </p>
</section>


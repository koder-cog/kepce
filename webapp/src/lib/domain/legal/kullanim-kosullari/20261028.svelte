<section class="uyari-kutusu">
  <h2>Menü, Fiyat ve Alerjen Bilgileri için Uyarı</h2>
  <p>
    Kepçe, Gençlik ve Spor Bakanlığı, Kredi ve Yurtlar Genel Müdürlüğü, İl
    Müdürlükleri veya üniversite yönetimleriyle hiçbir kurumsal bağı olmayan bir
    projedir. Buradaki yemekleri ben pişirmiyorum, yurt yemekhanelerinin
    mutfaklarına girip denetleme yetkim de yok.
  </p>
  <p>
    Sitedeki tüm tabldot menüleri, kalori ve gramaj miktarları ile fiyatlar ilgili
    kurumların kamuya açık duyurularından ve yurtdaşların katkılarından
    derlenir. Yemekhane kasasındaki turnike veya fiş fiyatı, tavan fiyat tarifesi,
    nöbetçi yurt düzenlemesi veya panodaki son dakika ilanı sitedeki bilgiden
    farklıysa her zaman fiziki yemekhanedeki durum geçerlidir.
  </p>
  <p>
    Resmi kurumlar yemeklerin laboratuvar analizlerini veya tam mutfak reçetelerini
    paylaşmadığından sitedeki <strong>alerjen ve diyet tahminleri</strong> yalnızca
    yemek isimlerinden algoritmik olarak türetilir ve bağlayıcı bir sağlık taahhüdü
    taşımaz. Aşçının o gün kıvam versin diye çorbaya un kavurması, farklı yağ
    kullanması veya mutfaktaki çapraz bulaşma riskleri tarafımdan bilinemez.
  </p>
  <p>
    Çölyak hastalığın, ağır gıda alerjin veya tıbbi hassasiyetin varsa sitedeki
    tahminlere ya da kullanıcı yorumlarına güvenerek asla karar verme. Yemeği
    yemeden önce mutlaka yemekhane personeliyle veya aşçıbaşıyla bizzat görüşüp
    içeriği teyit etmek senin sorumluluğundadır.
  </p>
</section>


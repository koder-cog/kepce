<section>
  <h2>2. Yaş ve Fiil Ehliyeti</h2>
  <p>
    Kepçe'deki kamuya açık yemek listelerini ve arşivleri incelemek herkese
    açıktır.
  </p>
  <p>
    Kepçe öncelikli olarak yükseköğrenim öğrencilerine hitap eder. Platformda
    hesap oluşturulması, veri paylaşılması veya yorum yazılması Türk Medeni
    Kanunu ile Türk Borçlar Kanunu uyarınca geçerli bir irade beyanı gerektirir.
    18 yaşından küçük bireylerin sisteme kayıt olması ve içerik paylaşması yasal
    temsilcilerinin iznine ve gözetimine bağlıdır. Reşit olmayan bir bireyin
    platformu izinsiz kullandığına dair haklı bir bildirim aldığımda
    ilgili hesabı ve içerikleri kaldırma hakkım saklıdır.
  </p>
</section>

<section>
  <h2>3. Yer Sağlayıcı Olarak Sorumluluk Sınırı</h2>
  <p>
    Kepçe, kamuya açık yemekhane menülerini sunarken İçerik Sağlayıcı, kullanıcı
    yorumları, oylamaları ve menü gönderimleri bakımından ise 5651 sayılı
    İnternet Kanunu kapsamında <strong>Yer Sağlayıcı</strong> sıfatıyla hizmet sunar.
  </p>
  <ul>
    <li>
      Gençlik ve Spor İl Müdürlükleri, KYK yurtları ve açık kaynak derlemelerinden
      toplanan <strong>menü verileri</strong> kaynak kartlarında açıkça gösterilir.
    </li>
    <li>
      Yemek listelerini dijitalleştirmek için sisteme gönderilen menü panosu
      fotoğrafları metne aktarıldıktan sonra kalıcı olarak silinir. Yemek
      değerlendirmelerine eklenen tabldot fotoğrafları ise konum bilgileri
      temizlenerek sitede yayımlanır. Sisteme aktarılan <strong
        >kullanıcı yüklemeleri</strong
      > içinde kişi yüzlerinin, öğrenci kimlik kartlarının veya ödeme fişlerinin
      yer almaması gerekir. Gönderdiğin belgelerin okunmasını, kırpılmasını ve
      kamuya açık yemek arşivine eklenmesini peşinen kabul etmiş sayılırsın.
    </li>
    <li>
      Kanun kapsamında içerik sağlayıcı sayılan kullanıcılar tarafından üretilen <strong
        >yorumlar ve oylar</strong
      > için önceden denetleme, editöryal süzgeçten geçirme veya doğruluk araştırması
      yapma yükümlülüğüm yoktur.
    </li>
  </ul>
</section>

<section>
  <h2>4. Hukuka Aykırı İçerik ve Uyar-Kaldır Bildirimleri</h2>
  <p>
    Kullanıcı içeriklerini önceden denetleme yükümlülüğüm bulunmamakla
    birlikte 5651 sayılı Kanun m. 5/2 uyarınca hukuka aykırı bir içerikten
    haberdar edildiğimde bu içeriği gecikmeksizin yayından kaldırmakla
    yükümlüyüm.
  </p>
  <p>
    Kişilik haklarının ihlali, telif ihlali, hakaret veya diğer mevzuata
    aykırılık iddialarını içeren bildirimlerini içeriklerin yanındaki bildir
    butonu üzerinden veya doğrudan
    <a href="mailto:yasal@kepce.org">yasal@kepce.org</a> adresine iletebilirsin. Bildirimin
    işleme alınabilmesi için ihlale konu içeriğin tam sayfa web bağlantısı, ihlal
    gerekçesinin somut açıklaması ve doğrulanabilir iletişim bilgilerin yer almalıdır.
  </p>
  <p>
    İletilen şikâyet ve bildirimler kişisel haberleşme sayılmaz. Hukuki
    inceleme, hak sahipliği teyidi ve yasal prosedürlerin yürütülmesi amacıyla
    gerekli görüldüğü takdirde ilgili taraflarla ve yetkili adli mercilerle
    paylaşılabilir.
  </p>
</section>

<section>

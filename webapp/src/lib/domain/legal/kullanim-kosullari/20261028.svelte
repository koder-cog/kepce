    kopyalayacak veya tam içeriğe ulaşmak için Kepçe'nin ziyaret edilmesi ihtiyacını
    ortadan kaldıracak boyutta olamaz.
  </p>
</section>

<section>
  <h2>6. Kullanıcı Kuralları ve Müdahale Yetkisi</h2>
  <p>
    Sisteme zarar verecek bot kullanımı, oy manipülasyonu, yetkisiz veri
    madenciliği, küfür, hakaret, başkalarının kişisel bilgilerini ifşa etme ve
    hukuka aykırı içerik yükleme girişimleri yasaktır. 5651 sayılı Kanun m. 4
    uyarınca sisteme yazdığın yorumların ve yüklediğin görsellerin cezai ve
    hukuki sorumluluğu bizzat sana aittir.
  </p>
  <p>
    Sitede paylaştığın yorum ve fotoğrafların platformda gösterilebilmesi için
    Kepçe'ye bu içerikleri yayımlama hakkı vermiş olursun. İstediğin zaman kendi
    yorumunu, fotoğrafını veya hesabını silebilirsin. Kuralların ihlali hâlinde
    hesabı askıya alma veya IP bazlı erişim kısıtlaması uygulama hakkı Kepçe'ye
    aittir.
  </p>
</section>

<section>
  <h2>7. Veri Ayrımı, Telif ve Marka Hakları</h2>
  <p>
    Platformdaki veriler kamuya açık bilgiler ve topluluk katkıları olmak üzere
    iki temel kategoriye ayrılır.
  </p>
  <ul>
    <li>
      KYK yurtları ve ilgili kamu kurumlarının duyurduğu ham yemek listeleri ile
      fiyat bilgileri gibi <strong>kamu verileri</strong> herkese açıktır ve telife
      konu değildir. Ancak bu verilerin doğrudan Kepçe sunucularından kontrolsüzce
      kazınması yerine API veya RSS kanallarının kullanılması, istek sınırlarına
      uyulması ve verinin kullanıldığı mecrada kepce.org adresine görünür atıf verilmesi
      şarttır.
    </li>
    <li>
      Kullanıcı yorumları, tabldot değerlendirmeleri, bot metinleri, sisteme
      yüklenen yemek fotoğrafları, besin eşleştirmeleri, arayüz tasarımları ve veri
      tabanı yapısı gibi <strong>özgün Kepçe içerikleri</strong> platforma ve
      topluluğa aittir. Bu içeriklerin izinsiz otomatik araçlarla kazınması,
      kopyalanması veya bir başkası tarafından kendi verisi gibi sunulması 5846
      sayılı FSEK Ek Madde 8 ve Türk Ticaret Kanunu m. 55 haksız rekabet hükümleri
      uyarınca yasaktır.
    </li>
  </ul>
  <p>
    Kepçe kaynak kodları AGPL v3 lisansıyla açık kaynak olsa da lisansın 7/e
    maddesi uyarınca proje adını, alan adını, logoyu ve görsel kimlik ögelerini
    kapsayan <strong>marka hakları</strong> saklıdır ve 6769 sayılı Sınai Mülkiyet
    Kanunu kapsamında korunur. Projeyi çatallayanlar resmi logoyu ve ismi kaldırıp
    kendi özgün markalarını kullanmakla yükümlüdür.
  </p>
</section>

<section>
  <h2>8. Hukuki Sorumluluk Sınırı</h2>
  <p>
    6098 sayılı Türk Borçlar Kanunu m. 115 uyarınca ağır kusur hâlleri saklı
    kalmak kaydıyla, hatalı fiyat yazımından, geciken menü duyurularından,
    nöbetçi yurt veya tedarik değişikliklerinden ya da otomatik alerjen ve diyet
    tahminlerinden kaynaklanabilecek hiçbir maddi zarardan veya sağlık
    probleminden Kepçe sorumlu tutulamaz. Yemekhane görevlilerinden bizzat teyit
    almadan yapılan tüketimlerin getirdiği tüm risk kullanıcıya aittir.
    Platformu kullanan herkes bu şartları peşinen kabul etmiş sayılır.
  </p>
</section>

<section>
  <h2>9. Trafik Kayıtları ve Sunucu Konumu</h2>
  <p>
    Kişisel verilerin işlenmesi ve şifrelenmesiyle ilgili ayrıntılı bilgi için
    <a href="/gizlilik-politikasi" data-link>Gizlilik Politikası</a> sayfasını inceleyebilirsin.
    Kamuya açık menüleri okuyan anonim ziyaretçilerden hiçbir IP kaydı alınmaz ve
    saklanmaz. Şehir tespiti sunucu belleğinde anlık olarak yapılır ve diske yazılmaz.
  </p>
  <p>
    Yorum yazan veya fotoğraf yükleyen kullanıcılara ait 5651 sayılı Kanun m.
    5/3 kapsamındaki IP adresi, port ve işlem zamanını içeren yasal trafik kayıtları
    en az bir ve en fazla iki yıl saklanır. Bu kayıtlar Fransa'daki sunucu diskine
    yazılmaz. Bellekte asimetrik şifreleme ile mühürlenerek doğrudan Türkiye'deki
    yerel arşive aktarılır ve Fransa belleğinden silinir. Yalnızca Türkiye Cumhuriyeti
    adli mercilerinin usulüne uygun resmi talebi üzerine Türkiye'deki anahtarla
    çözülerek paylaşılır. Çerezsiz anonim analiz için Umami ve bot koruması için
    Cloudflare kullanıldığında bu servislerin kendi güvenlik kuralları da geçerlidir.
  </p>
</section>

